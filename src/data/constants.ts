// Distance mapping helper (approximate km within Ahmedabad between reference zones/areas)
export function calculateAhmedabadDistance(userAreaName: string, itemAreaName: string): number {
  if (!userAreaName || userAreaName === 'All Ahmedabad') return 3.2;
  if (userAreaName.toLowerCase() === itemAreaName.toLowerCase()) return 0.8;

  const areaMap: Record<string, { x: number; y: number }> = {
    // Coordinate proxy: Vastrapur as center (0,0)
    vastrapur: { x: 0, y: 0 },
    bodakdev: { x: 1.2, y: 0.5 },
    satellite: { x: -0.5, y: -1.5 },
    thaltej: { x: 1.8, y: 2.2 },
    'prahlad-nagar': { x: -1.0, y: -3.5 },
    'prahlad nagar': { x: -1.0, y: -3.5 },
    anandnagar: { x: -0.8, y: -2.8 },
    jodhpur: { x: -0.2, y: -2.0 },
    shyamal: { x: -0.3, y: -2.2 },
    makarba: { x: -1.5, y: -4.5 },
    bopal: { x: -4.5, y: 1.0 },
    'south bopal': { x: -4.8, y: -0.5 },
    'south-bopal': { x: -4.8, y: -0.5 },
    ambli: { x: -3.0, y: 1.2 },
    navrangpura: { x: 2.5, y: -0.2 },
    'cg-road': { x: 3.2, y: -0.5 },
    'c.g. road': { x: 3.2, y: -0.5 },
    'ashram road': { x: 4.0, y: 0 },
    paldi: { x: 3.0, y: -2.5 },
    naranpura: { x: 2.8, y: 3.0 },
    usmanpura: { x: 3.5, y: 2.0 },
    'ellis bridge': { x: 3.5, y: -1.5 },
    sola: { x: 2.5, y: 4.5 },
    gota: { x: 3.0, y: 6.5 },
    chandkheda: { x: 6.0, y: 8.0 },
    motera: { x: 7.0, y: 7.5 },
    sabarmati: { x: 5.5, y: 5.0 },
    maninagar: { x: 8.5, y: -5.0 },
    vastral: { x: 11.0, y: -3.0 },
    nikol: { x: 12.0, y: 1.0 },
    bapunagar: { x: 9.5, y: 1.5 },
    odhav: { x: 13.0, y: -1.0 },
    juhapura: { x: 0.5, y: -5.0 },
    sarkhej: { x: -1.0, y: -6.0 },
    vatva: { x: 9.0, y: -8.0 },
    narol: { x: 7.5, y: -7.5 },
  };

  const key1 = userAreaName.toLowerCase().trim();
  const key2 = itemAreaName.toLowerCase().trim();

  const c1 = areaMap[key1] || { x: 0, y: 0 };
  const c2 = areaMap[key2] || { x: 3.5, y: 3.5 };

  const dx = c1.x - c2.x;
  const dy = c1.y - c2.y;
  const dist = Math.sqrt(dx * dx + dy * dy);
  return Math.max(0.6, Math.round(dist * 10) / 10);
}
